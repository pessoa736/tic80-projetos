layers={
 add=function(s, layer, id)
  if s[layer]==nil then s[layer]={} end
  table.insert(
   s[layer], 
   {
    id = item.id,
    draw = function(s) 
     item:draw() 
    end
   }
  )
 end,
 remove=function(s,layer,id)
  for k, i in ipairs(s[layer]) do
   if i.id==item.id then
    table.remove(s[layer], k)
   end
  end
 end,
 draw=function(s)
	 for k, i in ipairs(s) do
		 for k2, j in ipairs(i) do
			 j:draw()
			end
		end
	end
} 

